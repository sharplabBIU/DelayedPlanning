"""
Replication-based model recovery for the SOFT-GATED model family (Supp Fig S4,
softgate re-basing).

Identical procedure to model_recovery_reps.py (deterministic full-range parameter
grid, common random numbers, per-dataset iBIC winner over REPS datasets), with the
soft-gate rule substituted in BOTH directions:
  * fitting: the 13 candidates use the soft-gated likelihoods of
    study2/mfit_softgate_gen.py (generated by softgate_model_comparison.py:
    second-search counter accrues p1 * b2 per visit, state-tailored first-search
    urns) -- the exact likelihoods of the softgate model comparison (Fig 3A right);
  * generation: recovery_mbmc_sim.simulate_subject is source-patched with the same
    two changes (soft accrual + tailored urns), so every generating model is the
    corresponding soft-gated variant with off-model parameters disabled.
"""
