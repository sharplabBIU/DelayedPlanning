LABELS = [c[0] for c in CANDIDATES]
NUM_TRIALS = 60

# globals set in main(), inherited by fork workers
N_SUB = 60
REPS = 20
SS = 5000
MAXITER = 20
BASE_SEED = 400


def _simulate_dataset(gen_model, seed):
    truth = gen_params(gen_model, N_SUB, np.random.default_rng(seed))
    rows = []
    for i in range(N_SUB):
        r = S.simulate_subject(truth[i], SCAFFOLD, seed=seed * 100003 + i)
        for d in r:
            d['sub'] = i
        rows.extend(r)
    df = augment(pd.DataFrame(rows))
    return [df[df['sub'] == s].reset_index(drop=True) for s in range(N_SUB)]


def fit_dataset(task):
    """One replication: regenerate dataset, fit all candidates, return winner index."""
    gi, rep = task
    seed = BASE_SEED + gi * 10000 + rep
    dfs = _simulate_dataset(LABELS[gi], seed)
    ibics = np.array([em_fit_serial(dfs, pinfo, lik, SS, MAXITER, seed0=seed * 100 + ci)
                      for ci, (_, lik, pinfo) in enumerate(CANDIDATES)])
    return gi, int(np.argmin(ibics))


def main():
    global N_SUB, REPS, SS, MAXITER
    ap = argparse.ArgumentParser()
    ap.add_argument('--reps', type=int, default=REPS)
    ap.add_argument('--n', type=int, default=N_SUB)
    ap.add_argument('--ss', type=int, default=SS)
    ap.add_argument('--maxiter', type=int, default=MAXITER)
    ap.add_argument('--cores', type=int, default=max(1, (os.cpu_count() or 8) - 1))
    ap.add_argument('--smoke', action='store_true',
                    help='time a single MBMC_full dataset and exit')
    args = ap.parse_args()
    N_SUB, REPS, SS, MAXITER = args.n, args.reps, args.ss, args.maxiter

    if args.smoke:
        t0 = time.time()
        gi, wi = fit_dataset((len(LABELS) - 1, 0))
        print(f'smoke: gen=MBMC_full winner={LABELS[wi]}  '
              f'{time.time()-t0:.0f}s per dataset (ss={SS})', flush=True)
        return

    K = len(LABELS)
    tasks = [(gi, rep) for gi in range(K) for rep in range(REPS)]
    print(f'SOFTGATE recovery: {K} models x {REPS} datasets x {args.n} subj; '
          f'{len(tasks)*K} fits total; ss={SS}, maxiter={MAXITER}, cores={args.cores}',
          flush=True)

    counts = np.zeros((K, K))
    done = np.zeros(K, dtype=int)
    t0 = time.time()
    ctx = mp.get_context('fork')
    with ctx.Pool(args.cores) as pool:
        for gi, wi in pool.imap_unordered(fit_dataset, tasks):
            counts[gi, wi] += 1
            done[gi] += 1
            if done.sum() % 26 == 0:
                print(f'  {done.sum()}/{len(tasks)} datasets fit '
                      f'({time.time()-t0:.0f}s)', flush=True)
    conf = counts / REPS

    pd.DataFrame(conf, index=LABELS, columns=LABELS).to_csv(
        os.path.join(HERE, 'results', 'model_recovery_softgate_reps_confusion.csv'))
    print('\nProportion of %d datasets won by each model (rows=generating):' % REPS)
    print(pd.DataFrame(conf, index=LABELS, columns=LABELS).round(2).to_string())
    diag = np.diag(conf)
    print('\ndiagonal (self-recovery):', dict(zip(LABELS, np.round(diag, 2))))

    sns.set(style='white', font_scale=1.15)
    plt.figure(figsize=(9.5, 8))
    ax = sns.heatmap(conf, annot=True, fmt='.2f', cmap='viridis', vmin=0, vmax=1,
                     square=True, linewidths=0.5, xticklabels=LABELS, yticklabels=LABELS,
                     cbar_kws={'label': 'proportion of %d datasets won (iBIC)' % REPS,
                               'shrink': 0.8})
    ax.set_xlabel('Recovered (winning) model'); ax.set_ylabel('Generating model')
    ax.tick_params(axis='x', rotation=40); plt.setp(ax.get_xticklabels(), ha='right')
    ax.tick_params(axis='y', rotation=0)
    plt.title('Model recovery, soft-gated models: iBIC-winner proportion over '
              '%d datasets (N=%d each)' % (REPS, args.n))
    plt.tight_layout()
    plt.savefig(os.path.join(HERE, 'model_recovery_softgate_reps_study2.png'), dpi=300,
                bbox_inches='tight')
    plt.close()
    print(f'\nTotal {time.time()-t0:.0f}s. Saved: model_recovery_softgate_reps_study2.png, '
          'results/model_recovery_softgate_reps_confusion.csv')
    print('SOFTGATE MODEL RECOVERY DONE', flush=True)


if __name__ == '__main__':
    main()
